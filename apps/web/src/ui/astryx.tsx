/**
 * Astryx links (Link, a Button or menu item with `href`) go through Next's Link, so they move
 * between pages without a reload and add the base path. Astryx also hands the link a `to`, which
 * an anchor has no use for.
 */
const RouterLink = forwardRef<HTMLAnchorElement, ComponentProps<typeof NextLink> & {to?: unknown}>(function RouterLink({to: _to, ...props}, ref) {
  return <NextLink ref={ref} {...props} />;
});

/**
 * The Astryx theme (Sprint: Neutral with the indigo `ai` variant) for the whole app. The theme
 * module `../astryx-themes.ts` is generated by `npx astryx theme add`; don't edit it by hand.
 * Light mode only until dark mode is designed. Mounted inside the site's language provider.
 */
export function AstryxTheme({children}: {children: ReactNode}) {
  // Astryx's own words (Optional, Close, …) follow the site's language.
  const {locale} = useLocale();
  return (
    <InternationalizationProvider locale={locale === 'zh' ? 'zh-CN' : 'en'} messages={MESSAGES}>
      <Theme theme={themes[defaultThemeSlug]} mode="light">
        <LinkProvider component={RouterLink}>{children}</LinkProvider>
      </Theme>
    </InternationalizationProvider>
  );
}

const MESSAGES = {'zh-CN': zhCN};
