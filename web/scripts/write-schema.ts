// Writes the app's Postgres schema to ../db/schema.sql for the storage runtime.
import {writeFileSync} from 'node:fs';
import {SCHEMA_SQL, SCHEMA_VERSION} from '../src/data/schema.ts';

const out = new URL('../../db/schema.sql', import.meta.url);
writeFileSync(out, `-- Generated by \`npm run schema\` from web/src/data/schema.ts. Do not edit by hand.\n-- Schema version ${SCHEMA_VERSION}\n${SCHEMA_SQL.trim()}\n`);
console.log(`wrote ${out.pathname}`);
